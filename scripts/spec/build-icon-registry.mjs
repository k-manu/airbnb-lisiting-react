// Builds components/icon-art.generated.ts from design/spec/icons.json (see extract-icons.mjs).
// Each artwork gets a name from what it depicts (its label or place on the page), never from the
// reference's markup. Run: node scripts/spec/build-icon-registry.mjs
import { readFileSync, writeFileSync } from "node:fs";

const icons = JSON.parse(readFileSync("design/spec/icons.json", "utf8"));
const slug = (t) => t.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const AMENITY_ROWS = new Set(["Kitchen","Wifi","Dedicated workspace","Free parking on premises","Pool","Hot tub","Pets allowed","Exterior security cameras on property","Carbon monoxide alarm","Smoke alarm"]);

const named = new Map(); // name -> icon
const unnamed = [];

for (const ic of icons) {
  const l = ic.label;
  let name = null;
  if (l === "Airbnb homepage") continue; // the logo is already a supplied asset
  else if (l === "Choose a language and currency") name = "globe";
  else if (l === "Main navigation menu") name = "menu";
  else if (l === "Share") name = "share";
  else if (l === "Save") name = "heart";
  else if (l === "Guestfavourite") name = "laurel";
  else if (l === "Previous month") name = "chevron-small-left";
  else if (l === "Next month") name = "chevron-small-right";
  else if (ic.y === 5051) name = "verified";
  else if (l === "Clear dates") name = "keyboard";
  else if (l === "Report this listing") name = "flag";
  else if (l === "Search") name = "search";
  else if (l === "Zoom in") name = "plus";
  else if (l === "Zoom out") name = "minus";
  else if (l === "Back") name = "arrow-left";
  else if (l === "Close") name = "close";
  else if (l === "Previous") name = "chevron-left";
  else if (l === "Next") name = "chevron-right";
  else if (l.startsWith("Self check-in")) name = "door";
  else if (ic.w === 15 && ic.viewBox === "0 0 16 16") name = "dots-grid";
  else if (ic.w === 10 && ic.viewBox === "0 0 32 32") name = "star";
  else if (ic.viewBox === "0 0 18 18" && ic.w === 14) name = "chevron-more";
  else if (ic.y === 983 && !ic.overlay) name = "fire-pit";
  else if (ic.y === 1049 && !ic.overlay && !l) name = "fan";
  else if (ic.y === 924 && !ic.overlay) name = "chevron-down";
  else if (ic.y === 4368) name = "home-pin";
  else if (ic.y === 5244) name = "born";
  else if (ic.y === 5282) name = "school";
  else if (ic.y === 5351) name = "shield";
  else if (ic.y === 5522 && ic.x < 200) name = "rules-cancellation";
  else if (ic.y === 5522 && ic.x > 300 && ic.x < 600) name = "rules-house";
  else if (ic.y === 5522 && ic.x > 700) name = "rules-safety";
  else if (ic.y === 3098 && !ic.overlay) name = `category-${["cleanliness", "accuracy", "check-in", "communication", "location", "value"][Math.round((ic.x - 297) / 137)] ?? ic.x}`;
  else if (l && (AMENITY_ROWS.has(l) || ic.overlay === "What this place offers")) name = `amenity-${slug(l)}`;
  if (!name) { unnamed.push(ic); continue; }
  if (!named.has(name)) named.set(name, ic);
}

// Identical artwork under several names is written once and the other names become aliases.
const seen = new Map();
const aliases = {};
for (const [name, ic] of [...named.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  const key = ic.viewBox + ic.paint + ic.inner;
  if (seen.has(key)) { aliases[name] = seen.get(key); named.delete(name); } else seen.set(key, name);
}
const esc = (s) => JSON.stringify(s);
const camel = (k) => k.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const rootProps = (paint) => Object.fromEntries([...paint.matchAll(/([a-z-]+)="([^"]*)"/g)].map(([, k, v]) => [camel(k), v]));
const out = [`// GENERATED by scripts/spec/build-icon-registry.mjs from design/spec/icons.json (icon artwork of the`, `// reference listing: viewBox, paint and shape geometry only). Do not edit by hand.`, ``, `export interface IconArt {`, `  viewBox: string;`, `  /** Presentation attributes for the <svg> root (React prop names). */`, `  paint: Record<string, string>;`, `  /** The shapes, as SVG markup. */`, `  body: string;`, `}`, ``, `export const ICON_ART = {`];
for (const [name, ic] of [...named.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  const paint = rootProps(ic.paint);
  // Skip default-valued attributes to keep the file small.
  for (const [k, v] of Object.entries({ strokeLinecap: "butt", strokeLinejoin: "miter", fillRule: "nonzero", strokeMiterlimit: "4", opacity: "1" })) if (paint[k] === v) delete paint[k];
  if (paint.stroke === "none") delete paint.stroke;
  if (paint.strokeWidth === "1" && !paint.stroke) delete paint.strokeWidth;
  out.push(`  ${esc(name)}: { viewBox: ${esc(ic.viewBox)}, paint: ${JSON.stringify(paint)}, body: ${esc(ic.inner.replace(/<(\w+)([^>]*)><\/\1>/g, "<$1$2/>"))} },`);
}
out.push(`} satisfies Record<string, IconArt>;`, ``, `/** Names whose artwork is identical to another entry. */`, `export const ICON_ALIASES = ${JSON.stringify(aliases, null, 2)} as const;`, ``);
writeFileSync("components/icon-art.generated.ts", out.join("\n"));
console.log(`registry: ${named.size} artworks; unnamed: ${unnamed.length}`);
for (const u of unnamed) console.log(`  unnamed: y${u.y} x${u.x} ${u.w}x${u.h} vb ${u.viewBox} label "${u.label}"`);
console.log([...named.keys()].sort().join(", "));
