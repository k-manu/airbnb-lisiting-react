"""Generate data/gallery.generated.ts from design/capture/page-extract.json.

The extract holds only content + asset paths. Image sizes are read from the
files themselves. Re-run after replacing assets:  python scripts/generate-gallery-data.py
"""
import json
import os
import re

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
d = json.load(open("design/capture/page-extract.json", encoding="utf-8"))


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


rooms, photos = [], []
for r in d["tourRooms"]:
    rid = slug(r["name"])
    rooms.append({"id": rid, "name": r["name"], "details": r["details"]})
    for k, path in enumerate(r["photos"], start=1):
        w, h = Image.open("public" + path).size
        photos.append(
            {
                "id": os.path.splitext(os.path.basename(path))[0],
                "src": path,
                "alt": f"{r['name']}, photo {k} of {len(r['photos'])}",
                "width": w,
                "height": h,
                "roomId": rid,
            }
        )

featured = [os.path.splitext(os.path.basename(p))[0] for p in d["heroGrid"]]


def ts(v, indent=0):
    return json.dumps(v, ensure_ascii=False, indent=2).replace("\n", "\n" + " " * indent)


out = f"""// GENERATED by scripts/generate-gallery-data.py from design/capture/page-extract.json
// (content and asset paths only). Do not edit by hand.

import type {{ ListingPhoto, ListingRoom }} from "./types";

export const galleryRooms: ListingRoom[] = {ts(rooms)};

export const galleryPhotos: ListingPhoto[] = {ts(photos)};

/** The five photos shown in the hero grid, in grid order. */
export const featuredPhotoIds: string[] = {ts(featured)};
"""
open("data/gallery.generated.ts", "w", encoding="utf-8").write(out)
print(f"{len(rooms)} rooms, {len(photos)} photos, featured={[f[:8] for f in featured]}")
